#!/usr/bin/env python3
"""Generates k8s/41-grafana.yaml (dashboard JSON embedded in a ConfigMap).
Edit the PANELS list here, rerun, re-apply: the dashboard is code."""
import json
from pathlib import Path

DS = {"type": "prometheus", "uid": "prom"}

# (title, unit, [(expr, legend)], width)
PANELS = [
    ("Events detected (per hour)", "short",
     [("sum(increase(qd_events_total[1h]))", "events/h")], 8),
    ("Detection latency (origin to report)", "s",
     [("histogram_quantile(0.5, sum by (le) (increase(qd_detection_latency_seconds_bucket[1h])))", "median"),
      ("histogram_quantile(0.9, sum by (le) (increase(qd_detection_latency_seconds_bucket[1h])))", "90th pct")], 8),
    ("Stations delivering data (last 60 s)", "short",
     [("count(time() - qd_ingest_last_sample_unixtime < 60)", "stations")], 8),
    ("Data lag per station", "s",
     [("time() - qd_ingest_last_sample_unixtime", "{{station}}")], 24),
    ("PhaseNet inference per cycle", "s",
     [("rate(qd_picker_infer_seconds_sum[5m]) / rate(qd_picker_infer_seconds_count[5m])", "{{pod}}")], 12),
    ("Association time per run", "s",
     [("rate(qd_assoc_seconds_sum[5m]) / rate(qd_assoc_seconds_count[5m])", "PyOcto")], 12),
    ("Picks per minute", "short",
     [("60 * sum by (phase) (rate(qd_picker_picks_total[5m]))", "{{phase}}")], 12),
    ("Picks held for association", "short",
     [("qd_picks_held", "held")], 12),
    ("Scrape health (1 = up)", "short",
     [("up{job=\"quake\"}", "{{pod}}")], 24),
]


def dashboard():
    panels, x, y = [], 0, 0
    for i, (title, unit, targets, w) in enumerate(PANELS):
        if x + w > 24:
            x, y = 0, y + 8
        panels.append({
            "id": i + 1, "type": "timeseries", "title": title, "datasource": DS,
            "gridPos": {"h": 8, "w": w, "x": x, "y": y},
            "fieldConfig": {"defaults": {"unit": unit}, "overrides": []},
            "options": {"legend": {"displayMode": "list", "placement": "bottom"}},
            "targets": [{"refId": chr(65 + j), "datasource": DS, "expr": e, "legendFormat": l}
                        for j, (e, l) in enumerate(targets)],
        })
        x += w
    return {"uid": "quake", "title": "Quake detector", "schemaVersion": 39,
            "time": {"from": "now-3h", "to": "now"}, "refresh": "30s",
            "tags": ["quake"], "panels": panels}


def indent(text, n):
    return "\n".join(" " * n + line for line in text.splitlines())


DATASOURCE = """apiVersion: 1
datasources:
  - name: Prometheus
    uid: prom
    type: prometheus
    access: proxy
    url: http://prometheus:9090
    isDefault: true"""

PROVIDER = """apiVersion: 1
providers:
  - name: quake
    folder: Quake
    type: file
    options: {path: /var/lib/grafana/dashboards}"""

out = f"""# GENERATED by k8s/src/make_grafana.py -- edit that file, not this one.
# Grafana with its data source and dashboard provisioned from ConfigMaps.
#
# Open:  kubectl -n quake port-forward svc/grafana 3000:3000  ->  http://localhost:3000
# Anonymous viewing is on (local cluster only); admin login is admin / admin.
apiVersion: v1
kind: ConfigMap
metadata:
  name: grafana-provisioning
  namespace: quake
data:
  datasource.yaml: |
{indent(DATASOURCE, 4)}
  dashboards.yaml: |
{indent(PROVIDER, 4)}
---
apiVersion: v1
kind: ConfigMap
metadata:
  name: grafana-dashboards
  namespace: quake
data:
  quake.json: |
{indent(json.dumps(dashboard(), indent=2), 4)}
---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: grafana
  namespace: quake
spec:
  replicas: 1
  strategy: {{type: Recreate}}
  selector:
    matchLabels: {{app: grafana}}
  template:
    metadata:
      labels: {{app: grafana}}
    spec:
      containers:
        - name: grafana
          image: grafana/grafana:11.1.0
          env:
            - {{name: GF_AUTH_ANONYMOUS_ENABLED, value: "true"}}
            - {{name: GF_AUTH_ANONYMOUS_ORG_ROLE, value: Viewer}}
            - {{name: GF_DASHBOARDS_DEFAULT_HOME_DASHBOARD_PATH, value: /var/lib/grafana/dashboards/quake.json}}
          ports: [{{containerPort: 3000}}]
          volumeMounts:
            - {{name: provisioning, mountPath: /etc/grafana/provisioning/datasources/datasource.yaml, subPath: datasource.yaml}}
            - {{name: provisioning, mountPath: /etc/grafana/provisioning/dashboards/dashboards.yaml, subPath: dashboards.yaml}}
            - {{name: dashboards, mountPath: /var/lib/grafana/dashboards}}
          resources:
            requests: {{cpu: 50m, memory: 128Mi}}
            limits: {{memory: 512Mi}}
          readinessProbe:
            httpGet: {{path: /api/health, port: 3000}}
            periodSeconds: 10
      volumes:
        - name: provisioning
          configMap: {{name: grafana-provisioning}}
        - name: dashboards
          configMap: {{name: grafana-dashboards}}
---
apiVersion: v1
kind: Service
metadata:
  name: grafana
  namespace: quake
spec:
  selector: {{app: grafana}}
  ports: [{{port: 3000}}]
"""
Path(__file__).resolve().parent.parent.joinpath("41-grafana.yaml").write_text(out)
print("wrote k8s/41-grafana.yaml")
